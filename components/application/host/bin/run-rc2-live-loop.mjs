function hostStep(transcript, phase, result) {
  appendTranscriptStep(transcript, { phase, event: result.event, snapshot: result.snapshot, state: result.state })
}
function record(transcript, phase, request, modelResponse, state, extra = {}) {
  appendTranscriptStep(transcript, { phase, request, modelResponse: { ...modelResponse, ...extra }, state })
}
function modelStep(transcript, phase, request, response, result) {
  appendTranscriptStep(transcript, { phase, request, modelResponse: response, event: result.event, snapshot: result.snapshot, state: result.state })
}
async function writeJson(name, value) {
  await writeFile(resolve(outDir, name), JSON.stringify(value, null, 2) + '\n')
}

